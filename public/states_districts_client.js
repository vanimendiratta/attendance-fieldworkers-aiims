window.getAllIndianStates = function() {
  return Object.keys(window.INDIA_STATES_DISTRICTS).sort();
};

window.getDistrictsForIndianState = function(stateName) {
  if (!stateName) return [];
  if (window.INDIA_STATES_DISTRICTS[stateName]) {
    return window.INDIA_STATES_DISTRICTS[stateName];
  }
  const norm = stateName.trim().toLowerCase();
  const key = Object.keys(window.INDIA_STATES_DISTRICTS).find(
    k => k.toLowerCase() === norm || k.toLowerCase().replace(/[^a-z0-9]/g, "") === norm.replace(/[^a-z0-9]/g, "")
  );
  return key ? window.INDIA_STATES_DISTRICTS[key] : [];
};

/**
 * Helper to populate state dropdown and bind cascade to district dropdown
 */
window.setupStateDistrictCascade = function(stateSelectEl, districtSelectEl, options = {}) {
  if (!stateSelectEl || !districtSelectEl) return;

  const defaultStateText = options.defaultStateText || 'Select State / UT';
  const defaultDistrictText = options.defaultDistrictText || 'Select District';
  const allowAll = options.allowAll || false;

  // Populate States
  stateSelectEl.innerHTML = '';
  const statePlaceholder = document.createElement('option');
  statePlaceholder.value = allowAll ? 'ALL' : '';
  statePlaceholder.textContent = defaultStateText;
  stateSelectEl.appendChild(statePlaceholder);

  const states = window.getAllIndianStates();
  states.forEach(st => {
    const opt = document.createElement('option');
    opt.value = st;
    opt.textContent = st;
    stateSelectEl.appendChild(opt);
  });

  function updateDistricts(selectedState, selectedDistrictValue = '') {
    districtSelectEl.innerHTML = '';
    const distPlaceholder = document.createElement('option');
    distPlaceholder.value = allowAll ? 'ALL' : '';
    distPlaceholder.textContent = selectedState && selectedState !== 'ALL' 
      ? defaultDistrictText 
      : 'Select State First';
    districtSelectEl.appendChild(distPlaceholder);

    if (!selectedState || selectedState === 'ALL') {
      districtSelectEl.disabled = !allowAll;
      return;
    }

    districtSelectEl.disabled = false;
    const districts = window.getDistrictsForIndianState(selectedState);
    districts.forEach(dist => {
      const opt = document.createElement('option');
      opt.value = dist;
      opt.textContent = dist;
      if (selectedDistrictValue && selectedDistrictValue.toLowerCase() === dist.toLowerCase()) {
        opt.selected = true;
      }
      districtSelectEl.appendChild(opt);
    });
  }

  // Bind change handler
  stateSelectEl.addEventListener('change', (e) => {
    updateDistricts(e.target.value);
    if (typeof options.onStateChange === 'function') {
      options.onStateChange(e.target.value);
    }
  });

  if (typeof options.onDistrictChange === 'function') {
    districtSelectEl.addEventListener('change', (e) => {
      options.onDistrictChange(e.target.value);
    });
  }

  return {
    setValues: (state, district) => {
      if (state) {
        stateSelectEl.value = state;
        updateDistricts(state, district);
      } else {
        stateSelectEl.value = allowAll ? 'ALL' : '';
        updateDistricts('', '');
      }
    }
  };
};

window.initCascadingStateDistrictDropdowns = window.setupStateDistrictCascade;

// Standalone global handler for Duty State / UT -> Duty District dropdown cascade
window.handleStateChange = function(selectedState) {
  const distEl = document.getElementById('signupDistrict');
  if (!distEl) return;
  distEl.innerHTML = '';
  if (!selectedState) {
    distEl.innerHTML = '<option value="">Select State First</option>';
    return;
  }
  const placeholder = document.createElement('option');
  placeholder.value = '';
  placeholder.textContent = 'Select District';
  distEl.appendChild(placeholder);

  const districts = window.getDistrictsForIndianState(selectedState);
  (districts || []).forEach(d => {
    const opt = document.createElement('option');
    opt.value = d;
    opt.textContent = d;
    distEl.appendChild(opt);
  });
  distEl.disabled = false;
};

// Auto-attach listeners on DOMContentLoaded
if (typeof document !== 'undefined') {
  const initSignupStateCascade = () => {
    const stateEl = document.getElementById('signupState');
    if (stateEl) {
      stateEl.addEventListener('change', () => window.handleStateChange(stateEl.value));
      stateEl.addEventListener('input', () => window.handleStateChange(stateEl.value));
      if (stateEl.value) {
        window.handleStateChange(stateEl.value);
      }
    }
  };
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initSignupStateCascade);
  } else {
    initSignupStateCascade();
  }
}
